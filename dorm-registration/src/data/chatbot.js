const normalize = (s) => String(s || '').toLowerCase().replace(/\s+/g, '')

// หาหัวข้อที่ตรงกับข้อความมากที่สุด (คำค้นยาวได้คะแนนมากกว่า) — ไม่เจอคืน null
export function matchFaq(text) {
  const q = normalize(text)
  if (!q) return null
  let best = null
  let bestScore = 0
  for (const faq of FAQS) {
    const score = faq.keywords.reduce((sum, k) => (q.includes(normalize(k)) ? sum + normalize(k).length : sum), 0)
    if (score > bestScore) {
      best = faq
      bestScore = score
    }
  }
  return best
}
